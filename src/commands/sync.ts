// ── Helpers ───────────────────────────────────────────────────────────────────

function promptApprove(message: string): Promise<boolean> {
  return new Promise(resolve => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    rl.question(`${message}\nType APPROVE to continue: `, answer => {
      rl.close();
      resolve(answer.trim().toUpperCase() === 'APPROVE');
    });
  });
}

function extractStageTitleFromPlan(filePath: string): string {
  if (!fs.existsSync(filePath)) return '(TBD)';
  try {
    const content = fs.readFileSync(filePath, 'utf8');
    // Match: "Source Roadmap Stage: Stage X.Y (Title)" or bold variant
    const match = content.match(/\*{0,2}Source Roadmap Stage\*{0,2}\s*:\s*.*Stage\s+[\d.]+[^(]*\(([^)]+)\)/i);
    if (match) return match[1].trim();
    // Also handle "N/A"
    const naMatch = content.match(/\*{0,2}Source Roadmap Stage\*{0,2}\s*:\s*N\/A/i);
    if (naMatch) return '(TBD)';
    return '(TBD)';
  } catch {
    return '(TBD)';
  }
}

